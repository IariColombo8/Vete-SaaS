-- ============================================================================
-- Corrección puntual de VipVet a partir de "FABIAN_ALIMENTOS_2807_clasificado.xlsx".
--
-- El Excel original que se importó no distinguía qué alimentos se venden
-- sueltos por peso (el local abre la bolsa y pesa lo que pide el cliente) de
-- los que se venden como bolsa/caja cerrada. Este archivo clasificado sí lo
-- trae en la columna "PRESENTACION DE VENTA", junto con la cantidad real
-- (columna "CANTIDAD (KG)" o "CANTIDAD (UNIDADES)" según corresponda).
--
-- Es una corrección de UNA SOLA VEZ para los productos que ya están cargados
-- en la base de VipVet (identificados por el mismo "COD" del Excel original).
-- Las próximas veces que se reimporte la lista de precios del proveedor
-- (columna sin esta clasificación), el precio y el resto de los campos se
-- van a seguir actualizando con la lógica normal de `importar_productos` —
-- este script no cambia esa función ni afecta a otros tenants.
--
-- Qué hace cada bloque:
--
-- 1) "Por kilo/peso" (474 productos): pasan a `unidad = 'kg'`. El precio que
--    traía el Excel es el de la bolsa ENTERA, pero para `unidad = 'kg'` el
--    sistema interpreta `precio` como el precio POR KILO — así que acá se
--    recalcula (precio de bolsa ÷ CANTIDAD (KG)) en vez de copiarlo tal cual.
--    `peso_kg` se limpia porque ya no aplica (es un campo de bolsa cerrada).
--
-- 2) "Por unidad" (73 productos, cajas/packs con varias unidades adentro):
--    quedan con `unidad = 'un'` como ya estaban, y se completa
--    `unidades_por_bulto` con la columna "CANTIDAD (UNIDADES)" del Excel
--    (ej. una caja de 9 sobres).
--
-- 3) Tres filas del Excel sin código de proveedor: se matchean por nombre
--    exacto dentro de la categoría Alimentos, igual que hace
--    `importar_productos` cuando no hay código para buscar por él.
--
-- Quedaron 4 filas SIN corregir porque el propio Excel no trae con qué
-- calcular el precio por kilo — se completan a mano desde Productos:
--   - SILICA WONDERCAT BABY POWER / LAVANDA / NEUTRA (H&G): están medidas en
--     litros (3.8 LT), no en kilos — no hay una "CANTIDAD (KG)" con la que
--     convertir el precio de la bolsa a precio por kilo.
--   - "Kongo Gold Adulto x 8 kg": la columna de precio (VETER) viene vacía
--     en el Excel clasificado.
--
-- Generado a partir del Excel con `generar-correccion.js` (script de un solo
-- uso, no se guarda en el repo).
-- ============================================================================

